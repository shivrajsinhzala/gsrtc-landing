#!/usr/bin/env node
/**
 * Writes public/_redirects — the Cloudflare Pages redirect table.
 *
 * Why this exists rather than Astro's own `redirects` config: Astro's static redirects are HTML
 * pages carrying a `<meta http-equiv="refresh">`. A meta refresh is not a 301. Google does
 * eventually treat a persistent one as a permanent redirect, but it passes signals more slowly
 * and less reliably than a real status code — and every URL in this table is a page already
 * ranking under its old `.html` address. Cloudflare Pages reads `_redirects` and answers with a
 * true 301 at the edge, before any HTML is served.
 *
 * Generated rather than hand-written so it cannot drift from the pages that actually exist:
 * every slug here comes from the same data the routes are built from.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { PAGES } from '../src/data/pages.data.mjs';
import { HAND_WRITTEN_SLUGS } from '../src/data/slugs.mjs';

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(ROOT, 'public', '_redirects');

const slugs = [...HAND_WRITTEN_SLUGS, ...PAGES.map((p) => p.slug)].sort();
const seen = new Set();
const duplicates = slugs.filter((s) => (seen.has(s) ? true : (seen.add(s), false)));
if (duplicates.length) {
  console.error(`gen-redirects: duplicate slugs would emit conflicting rules: ${duplicates.join(', ')}`);
  process.exit(1);
}

const lines = [
  '# Generated by scripts/gen-redirects.mjs — do not edit by hand.',
  '#',
  '# Every URL below was live as `<slug>.html` and is indexed in Google under that address.',
  '# Cloudflare Pages answers these as real 301s at the edge, so the ranking those pages hold',
  '# follows them to their new extensionless URL instead of being dropped on the floor.',
  '',
  '# The old homepage spelling.',
  '/index.html    /    301',
  '',
  '# NOTE: `?lang=gu` is deliberately NOT handled here. Cloudflare Pages matches `_redirects`',
  '# on the path only — a query string in the "from" never matches, so a rule for it would look',
  '# correct and quietly do nothing. That old link is caught by a small shim on the homepage',
  '# instead (src/components/LegacyLangRedirect.astro), which is the one place it can be done',
  '# reliably.',
  '',
  '# Content pages: <slug>.html -> /<slug>',
  ...slugs.map((slug) => `/${slug}.html    /${slug}    301`),
  '',
];

fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, lines.join('\n'));
console.log(`gen-redirects: wrote ${slugs.length + 3} rules to public/_redirects`);
