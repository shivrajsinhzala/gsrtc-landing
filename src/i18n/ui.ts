export function useTranslations(lang: Locale) {
  // Gujarati falls back to English per key rather than per page: a missing translation should
  // show the English line, not an empty element.
  return { ...ui.en, ...ui[lang] } as typeof ui.en;
}

/**
 * A link to another page on this site, in the reader's language.
 *
 * Only the homepage exists in Gujarati today, so every other slug resolves to its English URL
 * whichever language the reader is in — a /gu/ URL that served English body copy would be a
 * worse outcome than an honest English link. See src/i18n/README.md.
 */
export function localeHref(lang: Locale, slug: string): string {
  if (slug === '') return lang === 'en' ? '/' : '/gu';
  return `/${slug}`;
}
